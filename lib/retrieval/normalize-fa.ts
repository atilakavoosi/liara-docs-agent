/**
 * نرمال‌سازی متن فارسی برای بازیابی واژگانی.
 *
 * چرا این فایل وجود داره: متن فارسی روی وب املای یکدست نداره. همون کلمه
 * ممکنه با «ی» عربی یا فارسی، با یا بدون نیم‌فاصله، و با ارقام عربی یا
 * لاتین نوشته بشه. بدون یکدست‌سازی، BM25 روی «کلید» و «كليد» دو ترم
 * متفاوت می‌بینه و بازیابی خراب می‌شه. این تابع روی هر دو سمت
 * (ایندکس و کوئری) اعمال می‌شه.
 */

const ARABIC_INDIC = /[٠-٩]/g; // ٠١٢٣٤٥٦٧٨٩
const PERSIAN_DIGITS = /[۰-۹]/g; // ۰۱۲۳۴۵۶۷۸۹
const DIACRITICS = /[ً-ْٰـ]/g; // اعراب و کشیدگی
const ZWNJ = /‌/g; // نیم‌فاصله

/**
 * نقطه‌گذاری که باید مرز کلمه بشه، نه بخشی از توکن.
 * `.` و `-` و `_` عمداً اینجا نیستن چون در توکن‌های فنی معنادارن
 * (`liara.json`، `text-embedding-3-small`).
 */
const PUNCT = /[؟،؛«»؞٪٬٫٭۔?!,;:"'()[\]{}<>|=+*^~`@#$&\\]/g;

/** حروفی که چند شکل املایی دارن و باید به یک شکل کانونی برسن */
const LETTER_MAP: Record<string, string> = {
  "ي": "ی", // ي عربی → ی فارسی
  "ى": "ی", // ى مقصوره → ی
  "ك": "ک", // ك عربی → ک فارسی
  "أ": "ا", // أ → ا
  "إ": "ا", // إ → ا
  "آ": "ا", // آ → ا
  "ة": "ه", // ة → ه
  "ؤ": "و", // ؤ → و
  "ئ": "ی", // ئ → ی
};

const LETTER_RE = new RegExp(`[${Object.keys(LETTER_MAP).join("")}]`, "g");

/** یکدست‌سازی متن، بدون تغییر معنا. روی متن انگلیسی بی‌اثره جز lowercase. */
export function normalizeFa(input: string): string {
  return input
    .normalize("NFKC")
    .replace(/^﻿/, "") // BOM
    .replace(LETTER_RE, (ch) => LETTER_MAP[ch])
    .replace(DIACRITICS, "")
    .replace(ARABIC_INDIC, (d) => String(d.charCodeAt(0) - 0x0660))
    .replace(PERSIAN_DIGITS, (d) => String(d.charCodeAt(0) - 0x06f0))
    .replace(ZWNJ, " ") // نیم‌فاصله مرز کلمه‌ست، نه حرف
    .replace(PUNCT, " ")
    .toLowerCase()
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * کلمات پرتکرار که سیگنال بازیابی ندارن.
 * «لیارا» عمداً اینجاست: در تقریباً هر سندی تکرار می‌شه، پس صفر قدرت
 * تفکیک داره ولی در کوئری‌های کاربر خیلی میاد و امتیازها رو به‌هم می‌ریزه.
 */
const STOPWORDS = new Set([
  "از", "به", "در", "که", "را", "با", "این", "است", "برای", "می", "تا", "بر",
  "یا", "هم", "شود", "شده", "کنید", "کند", "خود", "هر", "اگر", "بود", "باشد",
  "های", "ها", "یک", "و", "چطور", "چگونه", "چیست", "کنم", "لیارا", "liara",
  "the", "a", "an", "of", "to", "in", "is", "are", "for", "and", "or", "on",
  "with", "you", "how", "what", "can", "i", "my",
]);

/**
 * توکن‌سازی برای BM25. حروف فارسی/عربی، لاتین و ارقام نگه داشته می‌شن.
 * نقطه و خط تیره داخل توکن‌های فنی (`liara.json`، `text-embedding-3-small`)
 * عمداً حفظ می‌شن — این‌ها دقیقاً همون چیزهایی‌ن که کاربر دنبالشون می‌گرده.
 */
export function tokenize(input: string): string[] {
  const normalized = normalizeFa(input);
  const raw = normalized.match(/[؀-ۿa-z0-9][؀-ۿa-z0-9._-]*/g) ?? [];

  const out: string[] = [];
  for (const rawToken of raw) {
    const t = rawToken.replace(/^[._-]+|[._-]+$/g, ""); // نشانه‌های چسبیده به لبه
    if (t.length < 2 || STOPWORDS.has(t)) continue;
    out.push(t);

    // توکن‌های فنی نقطه/خط‌تیره‌دار املای یکدست ندارن: کاربر «Next.js»
    // می‌نویسه ولی مستندات «NextJS». پس شکل چسبیده و اجزا رو هم تولید
    // می‌کنیم تا هر دو املا به هم برسن. بدون این، کوئری «Next.js را
    // دیپلوی کنم» هیچ سند استقرار NextJS رو پیدا نمی‌کرد.
    if (/[._-]/.test(t)) {
      const joined = t.replace(/[._-]/g, "");
      if (joined.length > 1 && joined !== t) out.push(joined);
      for (const part of t.split(/[._-]+/)) {
        if (part.length > 1 && !STOPWORDS.has(part)) out.push(part);
      }
    }
  }
  return out;
}

/**
 * واژگان دوگانه‌ی فارسیِ فنی.
 *
 * توسعه‌دهنده‌ی فارسی‌زبان کلمه‌ی انگلیسی رو با حروف فارسی می‌نویسه
 * («دیپلوی»)، ولی مستندات رسمی معادل فارسی رو به‌کار می‌بره («استقرار»).
 * اندازه‌گیری شد: «دیپلوی» در **صفر** سند از ۲۳۵۸ تکه وجود داره، در حالی
 * که دقیقاً همون مفهوم پرتکرارترین موضوع مستندات لیاراست. بدون این نگاشت،
 * رایج‌ترین سؤال ممکن («چطور دیپلوی کنم») هیچ سند مرتبطی برنمی‌گردونه.
 *
 * فقط سمت کوئری اعمال می‌شه تا ایندکس بزرگ نشه.
 */
const SYNONYMS: Record<string, string[]> = {
  دیپلوی: ["استقرار", "deploy", "مستقر"],
  دپلوی: ["استقرار", "deploy"],
  deploy: ["استقرار", "دیپلوی"],
  استقرار: ["deploy", "دیپلوی"],
  دیتابیس: ["پایگاه", "داده", "database", "dbaas"],
  database: ["دیتابیس", "پایگاه", "داده"],
  ارور: ["خطا", "error", "مشکل"],
  error: ["خطا", "ارور"],
  خطا: ["error", "ارور"],
  کانفیگ: ["پیکربندی", "تنظیمات", "config"],
  config: ["پیکربندی", "تنظیمات", "کانفیگ"],
  تنظیمات: ["پیکربندی", "config"],
  اپ: ["برنامه", "اپلیکیشن", "app"],
  اپلیکیشن: ["برنامه", "app"],
  app: ["برنامه", "اپلیکیشن"],
  لاگ: ["گزارش", "log", "logs"],
  log: ["لاگ", "گزارش"],
  بکاپ: ["پشتیبان", "backup"],
  backup: ["بکاپ", "پشتیبان"],
  دامین: ["دامنه", "domain"],
  domain: ["دامنه", "دامین"],
  پلن: ["طرح", "تعرفه", "plan"],
  plan: ["پلن", "طرح", "تعرفه"],
  هزینه: ["قیمت", "تعرفه"],
  قیمت: ["هزینه", "تعرفه"],
  ریستارت: ["مجدد", "restart"],
  restart: ["ریستارت", "مجدد"],
  نصب: ["راه", "اندازی", "install"],
  install: ["نصب", "راه", "اندازی"],
  استوریج: ["ذخیره", "سازی", "storage"],
  storage: ["ذخیره", "سازی", "استوریج"],
  باکت: ["bucket", "فضا"],
  bucket: ["باکت", "فضا"],
  کلید: ["key", "توکن", "token"],
  key: ["کلید", "توکن"],
  توکن: ["token", "کلید"],
  اتصال: ["connect", "وصل", "کانکت"],
  connect: ["اتصال", "وصل"],
};

/**
 * توکن‌سازی کوئری کاربر با گسترش هم‌معنی.
 * فقط برای جستجو استفاده می‌شه؛ ساخت ایندکس از `tokenize` خام استفاده می‌کنه.
 */
export function tokenizeQuery(input: string): string[] {
  const base = tokenize(input);
  const expanded = new Set(base);
  for (const t of base) {
    for (const syn of SYNONYMS[t] ?? []) expanded.add(syn);
  }
  return [...expanded];
}

